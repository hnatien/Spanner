#!/bin/zsh
# Points development builds at your Apple Development certificate so macOS
# keeps privacy grants across rebuilds. Writes Config/Local.xcconfig
# (git-ignored). Create the certificate first: Xcode › Settings › Accounts ›
# your team › Manage Certificates… › + › Apple Development.
set -euo pipefail
cd "${0:A:h}/.."

identity=$(security find-identity -v -p codesigning | grep -m1 '"Apple Development:' | sed -E 's/.*"(Apple Development:[^"]*)".*/\1/' || true)
if [[ -z "$identity" ]]; then
  print -u2 "No Apple Development certificate found in your keychain."
  print -u2 "Create one in Xcode › Settings › Accounts › Manage Certificates…, then rerun."
  exit 1
fi

# The team ID is the certificate subject's organizational unit (OU).
team=$(security find-certificate -c "$identity" -p | openssl x509 -noout -subject -nameopt multiline \
  | awk -F' = ' '/organizationalUnitName/ { print $2; exit }')
if [[ ! "$team" =~ '^[A-Z0-9]{10}$' ]]; then
  print -u2 "Could not read a team ID from \"$identity\" (got \"$team\")."
  exit 1
fi

cat > Config/Local.xcconfig <<XCCONFIG
// Generated by scripts/setup-signing.sh for "$identity". Not committed.
SPANNER_SIGN_STYLE = Automatic
SPANNER_SIGN_IDENTITY = Apple Development
DEVELOPMENT_TEAM = $team
XCCONFIG
print "Signing with \"$identity\" (team $team). Wrote Config/Local.xcconfig."
